export const productBySlug = (slug: string) => PRODUCTS.find((product) => product.slug === slug);

export function unitPrice(product: Product, size?: string) {
  const factor = SIZES.find((s) => s.id === size)?.factor ?? 1;
  return Math.round(product.price * factor);
}

export const formatPrice = (cents: number) =>
  new Intl.NumberFormat("en-IE", { style: "currency", currency: "EUR" }).format(cents / 100);

// Responsive images, generated by scripts/fetch-images.mjs
export const HERO_WIDTHS = [800, 1200, 1600];
export const PRODUCT_WIDTHS = [400, 800];
export const heroSrcSet = () => HERO_WIDTHS.map((w) => `/images/hero-${w}.webp ${w}w`).join(", ");
export const productSrc = (slug: string, width = 800) => `/images/products/${slug}-${width}.webp`;
export const productSrcSet = (slug: string) => PRODUCT_WIDTHS.map((w) => `${productSrc(slug, w)} ${w}w`).join(", ");
export const HERO_SIZES = "100vw";
export const PRODUCT_PAGE_SIZES = "(min-width: 960px) 50vw, 100vw";

// The LCP image of a route. server.mjs preloads it from the HTML, so the browser fetches it
// while the JavaScript of the app downloads, instead of after the app renders the page.
export function lcpImageFor(pathname: string) {
  if (pathname === "/") return { href: "/images/hero-1200.webp", srcset: heroSrcSet(), sizes: HERO_SIZES };
  const slug = pathname.match(/^\/product\/([\w-]+)$/)?.[1];
  if (slug && productBySlug(slug)) {
    return { href: productSrc(slug, 800), srcset: productSrcSet(slug), sizes: PRODUCT_PAGE_SIZES };
  }
  return null;
}
