// Downloads the photos listed in photos.json from Unsplash, cropped and resized by its image
// CDN, into public/images/, and writes CREDITS.md. The output is committed, so the shop builds
// without network; run this again only to change the photos or their sizes.
// Usage: node scripts/fetch-images.mjs
import { mkdir, readFile, writeFile } from "node:fs/promises";
import { fileURLToPath } from "node:url";

const ROOT = new URL("../", import.meta.url);
const IMAGES = new URL("public/images/", ROOT);
const photos = JSON.parse(await readFile(new URL("photos.json", ROOT), "utf8"));

// Keep in sync with HERO_WIDTHS and PRODUCT_WIDTHS in src/products.ts
const HERO = { widths: [800, 1200, 1600], ratio: 9 / 16, quality: 70 };
const PRODUCT = { widths: [400, 800], ratio: 1, quality: 72 };

async function download(url, target) {
  const res = await fetch(url);
  if (!res.ok) throw new Error(`${res.status} for ${url}`);
  const body = Buffer.from(await res.arrayBuffer());
  await writeFile(target, body);
  return body.length;
}

await mkdir(new URL("products/", IMAGES), { recursive: true });
for (const photo of photos) {
  const spec = photo.slot === "hero" ? HERO : PRODUCT;
  for (const width of spec.widths) {
    const height = Math.round(width * spec.ratio);
    const url = `${photo.imageUrl}?w=${width}&h=${height}&fit=crop&crop=entropy&fm=webp&q=${spec.quality}`;
    const file = photo.slot === "hero" ? `hero-${width}.webp` : `products/${photo.slot}-${width}.webp`;
    const bytes = await download(url, new URL(file, IMAGES));
    console.log(`${file}  ${Math.round(bytes / 1024)} KB`);
  }
}

const credits = [
  "# Photo credits",
  "",
  "Photos from [Unsplash](https://unsplash.com), under the [Unsplash License](https://unsplash.com/license). Generated by `scripts/fetch-images.mjs` from `photos.json`.",
  "",
  "| Image | Photographer | Photo |",
  "|---|---|---|",
  ...photos.map((p) => `| ${p.slot} | ${p.photographer} | [${p.description}](${p.pageUrl}) |`),
  "",
].join("\n");
await writeFile(new URL("CREDITS.md", ROOT), credits);
console.log(`Credits written to ${fileURLToPath(new URL("CREDITS.md", ROOT))}`);
